using System.Globalization;
using System.Text;

namespace Auditor.Tools;

/// <summary>
/// Trivial baselines + scorer self-checks, written to evaluation/baseline_results.md. They exist only to give the real pipeline something to beat and to prove the scorer behaves:
///   B0  every case INCOMPLETE with no steps
///   B1  status copied from the workflow's reported_status (COMPLETE → COMPLETE, else INCOMPLETE), no steps
///   R1  (reference, uses gold) gold statuses with no steps  → shows how much of the score lives in the steps
///   R2  (reference, uses gold) gold exactly                  → must be 100% everywhere
///   R3  (reference, uses gold) gold steps in shuffled order  → sets perfect, sequence broken
/// R1-R3 read the labels on purpose and are NOT predictors.
/// </summary>
public static class Baselines
{
    private static string F1(double x) => (100 * x).ToString("F1", CultureInfo.InvariantCulture) + "%";

    public static string Build(string root)
    {
        var ds = Dataset.Load(Path.Combine(root, "dataset"), "sample_deletion_requests.csv");
        var gold = Scorer.ReadRows(Path.Combine(root, "dataset", "sample_output.csv"));
        var rng = new Random(0);
        List<(string Id, string Status, List<Step> Steps)> Rows(Func<Request, (string, List<Step>)> f) => ds.Requests.Select(r => { var (s, st) = f(r); return (r.CaseId, s, st); }).ToList();
        static Step ToStep(Scorer.RawStep s) => new((int)Convert.ToInt64(s.Get("step_no")), s.Text("phase"), s.Text("system_id"), s.Text("resource_id"), s.Text("operation"), s.Text("state"), s.Text("evidence_id"));
        var variants = new List<(string Name, List<(string Id, string Status, List<Step> Steps)> Rows)>
        {
            ("B0_all_incomplete_empty", Rows(r => ("INCOMPLETE", new()))),
            ("B1_reported_status_empty", Rows(r => (r.ReportedStatus == "COMPLETE" ? "COMPLETE" : "INCOMPLETE", new()))),
            ("R1_gold_status_no_steps", Rows(r => (gold[r.CaseId].Status, new()))),
            ("R2_gold_exact", Rows(r => (gold[r.CaseId].Status, gold[r.CaseId].Steps.Select(ToStep).ToList()))),
            ("R3_gold_steps_shuffled", Rows(r =>
            {
                var steps = gold[r.CaseId].Steps.Select(ToStep).ToList();
                for (int i = steps.Count - 1; i > 0; i--) { int j = rng.Next(i + 1); (steps[i], steps[j]) = (steps[j], steps[i]); }
                return (gold[r.CaseId].Status, steps);
            })),
        };
        var lines = new List<string>
        {
            "# Baseline results (32 labeled samples)", "",
            "Generated by `dotnet run --project code/tools/Auditor.Tools -- baselines`; every number below comes from that run.", "",
            "| variant | status acc (all) | status acc dev / not-tuned | step F1 strict | step F1 relaxed | resource F1 | exact rows | mean LCS strict | validator errors |",
            "|---|---|---|---|---|---|---|---|---|",
        };
        var detail = new List<string>();
        var splits = Scorer.AssignSplits(gold);
        var dev = gold.Keys.Where(c => splits[c] == "dev").OrderBy(c => c, StringComparer.Ordinal).ToList();
        var held = gold.Keys.Where(c => splits[c] == "heldout").OrderBy(c => c, StringComparer.Ordinal).ToList();
        var all = gold.Keys.OrderBy(c => c, StringComparer.Ordinal).ToList();
        string? b1Path = null;
        var tmp = Directory.CreateTempSubdirectory("baselines_").FullName;
        foreach (var (name, rows) in variants)
        {
            var path = Path.Combine(tmp, name + ".csv");
            OutputIo.Write(path, rows.Select(r => new OutputIo.Row(r.Id, r.Status, r.Steps)));
            if (name.StartsWith("B1", StringComparison.Ordinal)) b1Path = path;
            var errs = Validator.ValidateOutputFile(path, ds).Where(i => i.Severity == "error").ToList();
            var pred = Scorer.ReadRows(path);
            var m = Scorer.Score(gold, pred, all);
            var md = Scorer.Score(gold, pred, dev); var mh = Scorer.Score(gold, pred, held);
            lines.Add($"| {name} | {m.StatusCorrect}/{m.NCases} ({(100.0 * m.StatusCorrect / m.NCases).ToString("F1", CultureInfo.InvariantCulture)}%) | {md.StatusCorrect}/{md.NCases} / {mh.StatusCorrect}/{mh.NCases} | " +
                      $"{F1(m.StepStrict.F1)} | {F1(m.StepRelaxed.F1)} | {F1(m.Discovery.F1)} | {m.ExactCases}/{m.NCases} | {F1(m.MeanLcsFull)} | {errs.Count} |");
            if (errs.Count > 0) detail.Add($"* `{name}`: validator rejects it ({errs.Count} errors; codes: {string.Join(", ", errs.Select(i => i.Code).Distinct().OrderBy(c => c, StringComparer.Ordinal))})");
        }
        lines.AddRange(new[] { "", "Validator verdicts:", "" });
        lines.AddRange(detail.Count > 0 ? detail : new List<string> { "(all variants valid)" });
        lines.AddRange(new[]
        {
            "", "Interpretation:",
            "* B0/B1 are the floor: status is a coin-flip-ish guess and there are no steps, so every step metric is 0.",
            "* R1 shows that even a perfect status with empty steps scores 0 on all step metrics: the score lives in the steps.",
            "* R2 must be 100% everywhere (scorer sanity). R3 must keep step F1 at 100% but lose exact-row/LCS (scorer sees order).", "",
        });
        var (text, _) = Scorer.BuildReport(gold, Scorer.ReadRows(b1Path!), "both", 5, false, "B1_reported_status_empty (dev/not-tuned view)");
        lines.AddRange(new[] { "## Dev / not-tuned view of baseline B1", "", text });
        try { Directory.Delete(tmp, true); } catch (IOException) { }
        return string.Join("\n", lines) + "\n";
    }

    public static int Run(string[] args, TextWriter stdout, TextWriter stderr)
    {
        var root = Cli.Cli.RepoRoot();
        var text = Build(root);
        File.WriteAllText(Path.Combine(root, "code", "evaluation", "baseline_results.md"), text, new UTF8Encoding(false));
        stdout.WriteLine(text);
        return 0;
    }
}
