#!/usr/bin/env python3
"""Generate code/evaluation/performance_report.md from two `tools/profile_run.py --save` files (before and after the indexing work).

    python3 code/tools/profile_run.py --repeat 1 2 5 10 20 --runs 3 --save after.json      # on the current code
    python3 code/evaluation/performance_report.py --before before.json --after after.json

Every number in the report is read from those files (median of the runs of each scale; all runs are listed). The machine description is read from the
machine the report is generated on, so generate it where the benchmark ran. Nothing is estimated or extrapolated.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import platform
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

STAGES = [("evidence_parse", "parse evidence files"), ("classify_requests", "classify request text"), ("discovery_total", "timeline discovery (all cases at once)"),
          ("audit_cases_loop", "audit each case"), ("write_output", "write output.csv"), ("validate_output", "re-read and validate output.csv")]
SUB = [("discovery.case_inputs", "per-case inputs"), ("discovery.assign_accounts", "assign id-less accounts"), ("discovery.analytics", "assign anonymized analytics")]


def exponent(t1: float, n1: float, t2: float, n2: float) -> float | None:
    return math.log(t2 / t1) / math.log(n2 / n1) if t1 > 0 and t2 > 0 and n2 > n1 else None


def fmt_exp(e: float | None) -> str:
    return "-" if e is None else f"{e:.2f}"


def fit_line(xs: list[float], ys: list[float]) -> tuple[float, float, float]:
    """least squares y = a + b x; returns (a, b, R^2)"""
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx
    a = my - b * mx
    ss_res = sum((y - (a + b * x)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys) or 1e-12
    return a, b, 1 - ss_res / ss_tot


def stage(r: dict, key: str) -> float:
    return r["stages"].get(key, 0.0)


def build(before: list[dict], after: list[dict]) -> str:
    scales = [r["repeat"] for r in after]
    last = f"x{scales[-1]}"
    assert scales == [r["repeat"] for r in before], "before and after must cover the same scales"
    same = all(b["output_sha256"] == a["output_sha256"] for b, a in zip(before, after))
    L = ["# Performance report", "",
         "Generated by `code/evaluation/performance_report.py` from two `code/tools/profile_run.py --runs 3` benchmarks (fresh process per run, median reported). "
         "Nothing here is estimated: every number is a measurement on the machine below.", "",
         f"Machine: {platform.platform()}, {os.cpu_count()} logical CPUs, Python {platform.python_version()}. "
         "The auditor is single-threaded here (no model calls in these runs), so CPU count does not matter; absolute seconds do depend on the machine, the ratios are the finding.", "",
         "## 1. What was measured", "",
         "* **x1** is the real input: the 518 requests of `dataset/deletion_requests.csv` (plus the 32 sample requests the auditor always loads).",
         "* **x2 ... x20** repeat every request row K times under new case ids (`case_7__r3`), in a temporary folder where every other dataset file is linked unchanged. "
         "x20 is 10,360 requests. The repeated rows are the same people with the same evidence, so they are **not independent cases**: their answers differ from the real run "
         "(copies compete for the same free accounts). Only the cost is meaningful, not the statuses.",
         "* *Before* is the code at the start of the profiling work (commit `e34122c`) with only the stage timers added; *after* is the current code. "
         f"The output file is {'byte-identical' if same else '**NOT identical**'} between before and after at every scale (sha256 prefixes in the table), so the indexes changed the cost and nothing else.", "",
         "## 2. Wall time and peak memory", "",
         "| input | cases | before s (3 runs) | after s (3 runs) | speed-up | before / after growth vs x1 | peak RSS MB (after) | output sha256 |", "|---|---|---|---|---|---|---|---|"]
    for b, a in zip(before, after):
        L.append(f"| x{a['repeat']} | {a['cases']} | {b['total_s']:.2f} ({'/'.join(f'{x:.2f}' for x in b['runs_total_s'])}) | {a['total_s']:.2f} ({'/'.join(f'{x:.2f}' for x in a['runs_total_s'])}) | "
                 f"{b['total_s'] / a['total_s']:.2f}x | {b['total_s'] / before[0]['total_s']:.1f}x / {a['total_s'] / after[0]['total_s']:.1f}x | {a['peak_rss_mb']:.0f} | `{a['output_sha256'][:10]}` |")
    rss_gap = max(abs(b_["peak_rss_mb"] - a_["peak_rss_mb"]) for b_, a_ in zip(before, after))
    per_case_kb = 1024 * (after[-1]["peak_rss_mb"] - after[0]["peak_rss_mb"]) / (after[-1]["cases"] - after[0]["cases"])
    L += ["", "Peak memory is the process's peak resident set size (`ru_maxrss`), measured in its own fresh process. "
          + f"Before and after differ by at most {rss_gap:.1f} MB at any scale: the indexes are small next to the parsed evidence. "
          + f"It grows from {after[0]['peak_rss_mb']:.0f} MB at x1 to {after[-1]['peak_rss_mb']:.0f} MB at {last}, about {per_case_kb:.1f} KB per additional request.", "",
          "## 3. Where the time went, per stage (seconds, median run)", "",
          f"| stage | before x1 | before {last} | after x1 | after {last} | before growth x1 to {last} | after growth x1 to {last} |", "|---|---|---|---|---|---|---|"]
    b1, b20, a1, a20 = before[0], before[-1], after[0], after[-1]
    n_ratio = a20["cases"] / a1["cases"]
    for key, label in STAGES + SUB:
        pre = "&nbsp;&nbsp;" if key.startswith("discovery.") else ""
        gb = stage(b20, key) / stage(b1, key) if stage(b1, key) > 0.005 else None
        ga = stage(a20, key) / stage(a1, key) if stage(a1, key) > 0.005 else None
        L.append(f"| {pre}{label} (`{key}`) | {stage(b1, key):.3f} | {stage(b20, key):.3f} | {stage(a1, key):.3f} | {stage(a20, key):.3f} | "
                 f"{'-' if gb is None else f'{gb:.1f}x'} | {'-' if ga is None else f'{ga:.1f}x'} |")
    L += ["", f"Input grows {n_ratio:.0f}x from x1 to {last}, so a stage that grows about {n_ratio:.0f}x is linear, a stage far above that is super-linear, and a stage far below it is dominated by a fixed cost "
          "(parsing the evidence does not depend on the number of requests). Stages whose x1 time is below 5 ms show `-`: a ratio of two timer-noise values means nothing.", "",
          "### Cost per request after the change (microseconds, median run)", "",
          "| input | whole run | timeline discovery | per-case audit | validation | classification |", "|---|---|---|---|---|---|"]
    for a_ in after:
        us = lambda k, a=a_: f"{1e6 * stage(a, k) / a['cases']:.0f}"  # noqa: E731
        L.append(f"| x{a_['repeat']} | {1e6 * a_['total_s'] / a_['cases']:.0f} | {us('discovery_total')} | {us('audit_cases_loop')} | {us('validate_output')} | {us('classify_requests')} |")
    L += ["", "A linear stage has a flat column. The whole-run column falls at first because the fixed start-up cost is spread over more requests.", "",
          "## 4. Observed growth", "",
          "Local exponent p in time ~ cases^p between neighbouring scales (p = 1 is linear, p = 2 quadratic). Computed from the medians above; "
          "time includes the fixed start-up cost, which pulls p below 1 at small scales, so look at the large scales.", "",
          "| series | " + " | ".join(f"x{scales[i]} to x{scales[i + 1]}" for i in range(len(scales) - 1)) + " |", "|---|" + "---|" * (len(scales) - 1)]

    def row(label, ser):
        cells = []
        for i in range(len(scales) - 1):
            cells.append(fmt_exp(exponent(ser[i][1], ser[i][0], ser[i + 1][1], ser[i + 1][0])))
        return f"| {label} | " + " | ".join(cells) + " |"
    for which, data in (("before", before), ("after", after)):
        L.append(row(f"total, {which}", [(r["cases"], r["total_s"]) for r in data]))
        L.append(row(f"timeline discovery, {which}", [(r["cases"], stage(r, "discovery_total")) for r in data]))
    L.append(row("per-case audit loop, after", [(r["cases"], stage(r, "audit_cases_loop")) for r in after]))
    L.append(row("validation, after", [(r["cases"], stage(r, "validate_output")) for r in after]))
    L.append(row("classification, after", [(r["cases"], stage(r, "classify_requests")) for r in after]))
    xs = [float(r["cases"]) for r in after]
    a_fit, b_fit, r2 = fit_line(xs, [r["total_s"] for r in after])
    bb_fit = fit_line([float(r["cases"]) for r in before], [r["total_s"] for r in before])
    L += ["", f"Linear fit of the **after** totals, time = a + b * cases: a = {a_fit:.2f} s fixed, b = {1000 * b_fit:.3f} ms per request, R^2 = {r2:.4f}. "
          f"The same fit on the **before** totals: a = {bb_fit[0]:.2f} s, b = {1000 * bb_fit[1]:.3f} ms per request, R^2 = {bb_fit[2]:.4f}; "
          "the lower R^2 is the curvature the quadratic stages caused.", ""]
    exps_a = [e for i in range(len(after) - 1) if (e := exponent(stage(after[i], "discovery_total"), after[i]["cases"], stage(after[i + 1], "discovery_total"), after[i + 1]["cases"])) is not None]
    sub_b = stage(b20, "discovery_total") / max(stage(b1, "discovery_total"), 1e-9)
    sub_a = stage(a20, "discovery_total") / max(stage(a1, "discovery_total"), 1e-9)
    L += ["## 5. What was quadratic, and what was done about it", "",
          "Profiling (stage timers, `--cprofile`) found one stage whose cost per request grew with the input: the timeline discovery. The per-case audit, classification, writing and the fixed evidence parsing did not. "
          f"Discovery took {stage(b1, 'discovery_total'):.2f} s at x1 and {stage(b20, 'discovery_total'):.2f} s at {last} before ({sub_b:.0f}x for {n_ratio:.0f}x the input); "
          f"after: {stage(a1, 'discovery_total'):.2f} s and {stage(a20, 'discovery_total'):.2f} s ({sub_a:.0f}x). Indexes were built only for the loops that profiling showed:", "",
          "| where | quadratic because | index | same answers |", "|---|---|---|---|",
          "| account candidates (`discover.assign_accounts`) | every case scanned every account's delete events for its time window | events sorted once by time, a bisect per case | output sha256 identical at every scale |",
          "| account elimination and phase resolution | after every acceptance all unresolved cases were re-ranked and every claimant list rebuilt | inverted index account to claimant cases, a heap with lazy invalidation, memoized scores; the multi-pass order of the old loop is reproduced exactly | identical |",
          "| anonymized-analytics candidates | every case scanned every anonymization event, and for each pair `_foreign_chain` scanned every policy action of every user | events sorted by time (bisect), policy actions sorted by time (bisect over the next 25 minutes), result per event memoized | identical |",
          "| analytics elimination and phase | claimant lists rebuilt per case; rivals found by scanning all scored cases | precomputed claimant counts and a resource to cases index | identical |",
          "| cohort snapshot (`case_inputs`) | every case scanned every observation | one pass building file to profile-resources | identical |", "",
          f"**Residual growth, stated plainly.** After the change, discovery grew {stage(a20, 'discovery_total') / stage(a1, 'discovery_total'):.0f}x for {n_ratio:.0f}x the input from x1 to {last} "
          f"(overall exponent {fmt_exp(exponent(stage(a1, 'discovery_total'), a1['cases'], stage(a20, 'discovery_total'), a20['cases']))}) and is {100 * stage(a20, 'discovery_total') / a20['total_s']:.0f}% of the run at {last} "
          f"({stage(a20, 'discovery_total'):.2f} s of {a20['total_s']:.2f} s). Its neighbouring-scale exponents in section 4 jump around (between "
          f"{fmt_exp(min(exps_a))} and {fmt_exp(max(exps_a))}) because its times are a few hundred milliseconds and runs vary by a few percent: do not read them one by one. "
          "Validation shows the same effect at the top scale: its cost per request rises between the last two scales (table above), while the profiler's per-call cost of `validate_case` was flat "
          "(about 91 microseconds per call at x20 and 86 at x40 in two `--cprofile` runs, not stored in the benchmark files). That points to memory and garbage-collection pressure rather than an algorithm, "
          "but this was not isolated.", "",
          "Not indexed, on purpose: classification (a regex pass per request, linear: it is the largest remaining stage at the top scale), the per-case audit and validation (linear). "
          "No cache was added for repeated request text, because that would only help the artificial repeated-row input, not real data.", "",
          "## 6. What is NOT scaled - read this before relying on the numbers", "",
          "This is a **batch auditor, not a service**. It reads one dataset, writes one `output.csv` and exits.", "",
          "* **Everything is held in memory** in one process: all evidence observations, the whole activity stream, every request. Memory grows linearly with cases (above) and with evidence, and nothing is paged to disk.",
          "* **Single process, single thread.** There is no parallelism over cases; the only concurrency in the code is the bounded pool for reading screenshots (`llm.max_concurrency`) with a vision model (not exercised in these runs).",
          "* **Discovery is global.** Assigning an id-less account or analytics record to a case needs the other cases (elimination), so cases cannot be audited in independent shards, and adding one request can change another case's answer. A service answering one request at a time would need a different design.",
          "* **Only the requests were scaled.** The evidence files (103 files, 4 MB), the activity stream (a few thousand rows) and the identity tables were NOT scaled. Their parsing is a fixed cost here (about "
          f"{stage(a1, 'evidence_parse'):.2f} s); a dataset with 10x the evidence would pay that 10x, and no growth law for it was measured. Quadratic behaviour in the number of evidence files, activity rows or users may exist and was not tested.",
          "* **The repeated rows are not independent data** (same people and evidence). Real 10,000-request data would have more distinct accounts and evidence; the timings show the cost of the algorithms on this shape of data, not a forecast for other data.",
          "* **Model latency and cost are not benchmarked.** These runs used no vision model (no API key was available). Reading screenshots would add one model call per PNG (11 in this dataset) at network latency; the concurrency bound, 429 backoff and cache are tested with a fake client only.",
          "* **No behaviour under failure at scale** (disk full, huge request text, adversarial inputs) was measured beyond the robustness tests.", "",
          "## 7. Reproduce", "",
          "```text", "python3 code/tools/profile_run.py --repeat 1 2 5 10 20 --runs 3 --save after.json --table",
          "python3 code/evaluation/performance_report.py --before before.json --after after.json", "```", "",
          "`before.json` was produced the same way on a checkout of commit `e34122c` with only the stage timers added (`code/tools/profile_run.py` needs `Auditor.timings`). Absolute seconds vary by machine and by load; "
          "run the two benchmarks back to back, as was done here, when comparing."]
    return "\n".join(L) + "\n"


def wall_time_table(report_text: str) -> str:
    """The section-2 table of a generated report (header row to last row), verbatim."""
    lines = report_text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("| input | cases |"))
    end = start
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    return "\n".join(lines[start:end])


MARK = ("<!-- perf-table:start -->", "<!-- perf-table:end -->")


def put_table(architecture: str, table: str) -> str:
    a, b = architecture.index(MARK[0]) + len(MARK[0]), architecture.index(MARK[1])
    return architecture[:a] + "\n\n" + table + "\n\n" + architecture[b:]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--before", type=Path, required=True)
    ap.add_argument("--after", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=ROOT / "code" / "evaluation" / "performance_report.md")
    ap.add_argument("--architecture", type=Path, default=ROOT / "ARCHITECTURE.md", help="also copy the wall-time table into this file between the perf-table markers")
    a = ap.parse_args(argv)
    before, after = (json.loads(p.read_text(encoding="utf-8")) for p in (a.before, a.after))
    text = build(before, after)
    a.out.write_text(text, encoding="utf-8")
    if a.architecture and a.architecture.exists():
        a.architecture.write_text(put_table(a.architecture.read_text(encoding="utf-8"), wall_time_table(text)), encoding="utf-8")
    print(f"wrote {a.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
