#!/usr/bin/env python3
"""Trivial baselines + scorer self-checks, written to evaluation/baseline_results.md.

These exist only to give the real pipeline something to beat and to prove the scorer behaves:
  B0  every case INCOMPLETE with no steps
  B1  status copied from the workflow's reported_status (COMPLETE -> COMPLETE, else INCOMPLETE), no steps
  R1  (reference, uses gold) gold statuses with no steps  -> shows how much of the score lives in the steps
  R2  (reference, uses gold) gold exactly                  -> must be 100% everywhere
  R3  (reference, uses gold) gold steps in shuffled order  -> sets perfect, sequence broken
R1-R3 read the labels on purpose and are NOT predictors.
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from auditor.dataset import load_dataset  # noqa: E402
from auditor.outio import write_output  # noqa: E402
from auditor.validate import validate_output_file  # noqa: E402
from score import assign_splits, build_report, read_rows, score  # noqa: E402

OUT = ROOT / "code" / "out"


def b0(ds):
    return [(r.case_id, "INCOMPLETE", []) for r in ds.requests]


def b1(ds):
    return [(r.case_id, "COMPLETE" if r.reported_status == "COMPLETE" else "INCOMPLETE", []) for r in ds.requests]


def main() -> int:
    ds = load_dataset(ROOT / "dataset", "sample_deletion_requests.csv")
    gold = read_rows(ROOT / "dataset" / "sample_output.csv")
    rng = random.Random(0)
    shuffled = []
    for r in ds.requests:
        steps = [dict(s) for s in gold[r.case_id].steps]
        rng.shuffle(steps)
        shuffled.append((r.case_id, gold[r.case_id].status, steps))
    variants = {
        "B0_all_incomplete_empty": b0(ds),
        "B1_reported_status_empty": b1(ds),
        "R1_gold_status_no_steps": [(r.case_id, gold[r.case_id].status, []) for r in ds.requests],
        "R2_gold_exact": [(r.case_id, gold[r.case_id].status, gold[r.case_id].steps) for r in ds.requests],
        "R3_gold_steps_shuffled": shuffled,
    }
    lines = ["# Baseline results (32 labeled samples)", "",
             "Generated by `python3 code/evaluation/baseline.py`; every number below comes from that run.", "",
             "| variant | status acc (all) | status acc dev / not-tuned | step F1 strict | step F1 relaxed | resource F1 | exact rows | mean LCS strict | validator errors |",
             "|---|---|---|---|---|---|---|---|---|"]
    detail = []
    for name, rows in variants.items():
        path = OUT / f"{name}.csv"
        write_output(path, rows)
        issues = validate_output_file(path, ds)
        errs = [i for i in issues if i.severity == "error"]
        pred = read_rows(path)
        m = score(gold, pred, sorted(gold))
        sp = assign_splits(gold)
        md = score(gold, pred, sorted(c for c in gold if sp[c] == "dev"))
        mh = score(gold, pred, sorted(c for c in gold if sp[c] == "heldout"))
        lines.append(f"| {name} | {m.status_correct}/{m.n_cases} ({100*m.status_correct/m.n_cases:.1f}%) | "
                     f"{md.status_correct}/{md.n_cases} / {mh.status_correct}/{mh.n_cases} | {100*m.step_strict[2]:.1f}% | "
                     f"{100*m.step_relaxed[2]:.1f}% | {100*m.discovery[2]:.1f}% | {m.exact_cases}/{m.n_cases} | {100*m.mean_lcs_full:.1f}% | {len(errs)} |")
        if errs:
            kinds = sorted({i.code for i in errs})
            detail.append(f"* `{name}`: validator rejects it ({len(errs)} errors; codes: {', '.join(kinds)})")
    lines += ["", "Validator verdicts:", ""] + (detail or ["(all variants valid)"])
    lines += ["", "Interpretation:",
              "* B0/B1 are the floor: status is a coin-flip-ish guess and there are no steps, so every step metric is 0.",
              "* R1 shows that even a perfect status with empty steps scores 0 on all step metrics: the score lives in the steps.",
              "* R2 must be 100% everywhere (scorer sanity). R3 must keep step F1 at 100% but lose exact-row/LCS (scorer sees order).",
              ""]
    text, _ = build_report(gold, read_rows(OUT / "B1_reported_status_empty.csv"), "both", 5, False, "B1_reported_status_empty (dev/not-tuned view)")
    lines += ["## Dev / not-tuned view of baseline B1", "", text]
    (ROOT / "code" / "evaluation" / "baseline_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
