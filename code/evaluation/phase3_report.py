#!/usr/bin/env python3
"""Phase 3 measurements -> evaluation/phase3_results.md (every number comes from this run unless marked "Phase 2 snapshot").

  python3 code/evaluation/phase3_report.py

Sections
  1  sample scores (dev / not-tuned / all) and ablations of the discovery stages
  2  the four questions asked before iterating: (a) can a missing account step change the status, (b) predicted status counts main vs
     samples, (c) does any finding depend on later-evidence linking, (d) precision of elimination (hold-out) and how many main rows
     depend on it
  3  accounts / analytics discovery: how each main row was resolved, hold-out precision, rows that stay unresolved
  4  expected F1 effect of guessing among k candidates versus omitting (behaviour is NOT changed)
  5  remaining failures on the dev samples
"""
from __future__ import annotations

import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from auditor.audit import Auditor, Config  # noqa: E402
from auditor.dataset import load_requests  # noqa: E402
from holdout import HEADER, account_holdout, analytics_holdout, f1_effect_of_guessing  # noqa: E402
from phase2_report import as_rows, classify_missing, metrics_line, pct, run  # noqa: E402
from score import assign_splits, read_rows, score  # noqa: E402

D = ROOT / "dataset"
OUT = ROOT / "code" / "evaluation"

# Phase 2 snapshot: measured with the scratch script at the start of Phase 3 on commit 8d4d389 (before any Phase 3 change).
P2 = {"steps": 3020, "missing_account_rows": 138, "ambiguous": 100, "none": 38, "k": {2: 72, 3: 24, 4: 1, 6: 3},
      "loo_single": "142/142 correct (45 more had no delete event; 2 ambiguous)", "holdout30": "1152/1152 correct (528 omitted)", "holdout50": "1804/1804 (1016 omitted)"}


def main() -> int:
    gold = read_rows(D / "sample_output.csv")
    split = assign_splits(gold)
    ids = {"dev": sorted(c for c in gold if split[c] == "dev"), "not-tuned": sorted(c for c in gold if split[c] == "heldout"), "all": sorted(gold)}
    main_ids = [r.case_id for r in load_requests(D / "deletion_requests.csv")]
    L = ["# Phase 3 results (generated by `python3 code/evaluation/phase3_report.py`)", "",
         "Every number is from this run, except the block marked *Phase 2 snapshot* (measured on commit 8d4d389 before Phase 3 changed anything).",
         "Failures of the not-tuned sample cases are never listed (aggregate only).", ""]

    # ------------------------------------------------------------ 1. scores and ablations
    variants = {
        "full pipeline (Phase 3)": Config(),
        "no seconds-phase stages": Config(use_timing_heuristics=False),
        "with cohort-snapshot narrowing (Phase 2 default)": Config(use_cohort_filter=True),
        "no later-evidence linking (D3 off)": Config(allow_later_linking=False),
        "no timeline discovery": Config(use_discovery=False),
    }
    L += ["## 1. Labeled samples (32): scores and ablations", "",
          "| variant / split | cases | status | step P | step R | step F1 | resource-discovery F1 | exact rows | mean LCS |",
          "|---|---|---|---|---|---|---|---|---|"]
    full = None
    for name, cfg in variants.items():
        a, res = run(cfg, ids["all"])
        pred = as_rows(res)
        for sp in ("dev", "not-tuned", "all"):
            L.append(metrics_line(f"{name} / {sp}", gold, pred, ids[sp]))
        if full is None:
            full = (a, res)
    L += ["", "Phase 2 reference (same split): dev F1 97.7% (P 100%, R 95.6%), not-tuned F1 98.2%, all 32 status 32/32.", ""]

    # ------------------------------------------------------------ main-set run
    a_full = Auditor(D, Config())
    res_main = {c: a_full.audit(c) for c in main_ids}
    res_samp = full[1]
    dele = [c for c in main_ids if a_full.classification[c].label == "DELETION"]
    fallbacks = [c for c in main_ids if res_main[c].provisional or any(n.startswith("FALLBACK") for n in res_main[c].notes)]
    no_acct = [c for c in dele if not any(s["system_id"] == "account_service" for s in res_main[c].steps)]
    no_acct_real = [c for c in no_acct if c not in fallbacks]

    # ------------------------------------------------------------ 2. the four questions
    obs_up = [o for o in a_full.base.obs if o.category == "USER_PROFILE"]
    idless = collections.Counter(o.state for o in obs_up if not o.idents)
    unlinked_present = sorted({o.resource for o in obs_up if o.state == "PRESENT" and not a_full.link.resource_users.get(o.resource)})
    L += ["## 2. The questions asked before iterating", "",
          "### (a) Could a missing account step change `deletion_status`?", "",
          f"* USER_PROFILE observations without any identifier: {dict(idless)}. **None is PRESENT**: a present account always carries an identifier, so it is "
          "linked by identity and its violation is already found. The accounts the timeline discovery looks for are therefore always ABSENT, and an ABSENT account "
          "is only ever a `VERIFY_RECORD_ABSENT` step (never a finding), so it cannot move a row from COMPLETE to INCOMPLETE.",
          f"* PRESENT accounts that belong to nobody in `user_identities`/audit log (their e-mails match no request either): {unlinked_present} - decoys, not requests.",
          f"* Rows with a deletion request but no account step now: **{len(no_acct)}** ({len(no_acct) - len(no_acct_real)} of them provisional rows (screenshot-only requests; "
          f"the ninth has an account step) waiting for the PNG reading; {len(no_acct_real)} real misses). Phase 2 snapshot: {P2['missing_account_rows']} rows.",
          f"* Status of the {len(no_acct_real)} real misses: {dict(collections.Counter(res_main[c].status for c in no_acct_real))}. Status flips possible from the account: **0**; "
          "what is lost is one `VERIFY_RECORD_ABSENT` step per row (see section 4 for the F1 cost).", ""]

    cross = collections.Counter()
    for c in main_ids:
        cross[("main", a_full.requests[c].reported_status, res_main[c].status)] += 1
    for c in ids["all"]:
        cross[("samples", a_full.requests[c].reported_status, res_samp[c].status)] += 1
    L += ["### (b) Predicted status counts, main vs samples", "",
          "| set | COMPLETE | INCOMPLETE | NOT_APPLICABLE | rows |", "|---|---|---|---|---|"]
    for name, rs in (("main (518)", res_main), ("samples (32), predicted", res_samp)):
        cnt = collections.Counter(r.status for r in rs.values())
        L.append(f"| {name} | {cnt['COMPLETE']} ({pct(cnt['COMPLETE'] / len(rs))}) | {cnt['INCOMPLETE']} ({pct(cnt['INCOMPLETE'] / len(rs))}) | {cnt['NOT_APPLICABLE']} ({pct(cnt['NOT_APPLICABLE'] / len(rs))}) | {len(rs)} |")
    gcnt = collections.Counter(g.status for g in gold.values())
    L.append(f"| samples (32), gold | {gcnt['COMPLETE']} ({pct(gcnt['COMPLETE'] / 32)}) | {gcnt['INCOMPLETE']} ({pct(gcnt['INCOMPLETE'] / 32)}) | {gcnt['NOT_APPLICABLE']} | 32 |")
    L += ["", "Predicted status by the workflow's `reported_status` (the claim; never used as evidence):", "",
          "| set | reported_status | COMPLETE | INCOMPLETE | NOT_APPLICABLE |", "|---|---|---|---|---|"]
    for sname in ("main", "samples"):
        for rep in ("COMPLETE", "PARTIALLY_COMPLETE", "NOT_STARTED"):
            L.append(f"| {sname} | {rep} | " + " | ".join(str(cross[(sname, rep, s)]) for s in ("COMPLETE", "INCOMPLETE", "NOT_APPLICABLE")) + " |")
    n_na = sum(1 for r in res_main.values() if r.status == "NOT_APPLICABLE")
    L += ["", f"Of the {n_na} NOT_APPLICABLE rows in the main set, {sum(1 for c in main_ids if a_full.classification[c].label != 'DELETION')} are requests that do not authorize deletion "
          f"and {len(fallbacks)} are conservative fallbacks for deletion requests whose only evidence is a PNG (as of Phase 4 these are provisional INCOMPLETE rows, not NOT_APPLICABLE); "
          "the samples contain no non-deletion request.", ""]

    # (c) later-evidence invariant
    a_nol = Auditor(D, Config(allow_later_linking=False))
    added = collections.Counter()
    flips = 0
    for c in main_ids + ids["all"]:
        r1, r0 = a_full.audit(c), a_nol.audit(c)
        k1 = {(s["phase"], s["operation"], s["system_id"], s["resource_id"]) for s in r1.steps}
        k0 = {(s["phase"], s["operation"], s["system_id"], s["resource_id"]) for s in r0.steps}
        flips += r1.status != r0.status
        for k in k1 - k0:
            added[f"{k[0]} {k[1]}"] += 1
    L += ["### (c) Does any FINDING depend on later-evidence linking?", "",
          f"Steps that exist only because evidence captured after `audit_at` tied a resource to the user (main + samples): **{dict(added)}**; status changes caused by it: **{flips}**.",
          "No FINDING or REMEDIATION step and no status depends on it: it only adds end-state `VERIFY_RECORD_*` steps, none of them cited. "
          "This is now enforced twice: `_audit` refuses to report a violation on a record linked only by later evidence, and "
          "`tests/test_pipeline.py::LaterEvidenceInvariant` re-runs all 550 cases with and without later linking and asserts identical statuses, findings and remediations.", ""]

    # (d) elimination
    how_main = collections.Counter(a_full.account_asg[c].how for c in dele if c in a_full.account_asg)
    how_ana = collections.Counter(a_full.analytics_asg[c].how for c in main_ids if c in a_full.analytics_asg)
    seeds = range(30)
    loo = account_holdout(a_full, 1.0, range(1))                # every eligible case hidden at once = worst case
    h30 = account_holdout(a_full, 0.3, seeds)
    h50 = account_holdout(a_full, 0.5, seeds)
    h30_cohort = account_holdout(a_full, 0.3, seeds, use_cohort=True)
    h30_nophase = account_holdout(a_full, 0.3, seeds, use_timing_heuristics=False)
    L += ["### (d) Precision of the elimination heuristic and how many main rows depend on it", "",
          "Method (`evaluation/holdout.py`): cases whose account is linked explicitly (that link is the label) are hidden at random, the real discovery code runs, "
          "and each hidden case is `correct`, `wrong`, `stolen` (the hidden case's account was given to another case) or `omitted`. "
          "The Phase 2 measurement counted only the hidden case; it could not see a case that kept an account belonging to a labeled sample "
          "(found at the start of Phase 3 on a labeled sample: an account linked only by a later snapshot was handed to a neighbour). "
          "`stolen` closes that blind spot.", "",
          *HEADER,
          loo.line("all eligible cases hidden at once (1 run)"),
          h30.line("30% hidden x 30 seeds, final pipeline"), h50.line("50% hidden x 30 seeds, final pipeline"),
          h30_nophase.line("30% x 30, elimination only (no seconds-phase)"),
          h30_cohort.line("30% x 30, with cohort-snapshot narrowing (Phase 2 default)"), "",
          f"Phase 2 snapshot (per-case scoring only): single leave-one-out {P2['loo_single']}; 30% hidden {P2['holdout30']}; 50% hidden {P2['holdout50']}.", "",
          "* Elimination is exact when the true account is among the candidates; what breaks it is a candidate set that was wrongly narrowed. "
          "Cohort-snapshot narrowing, the Phase 2 default, **fails this test** (precision in the row above) and is switched off by default; "
          "when narrowing leaves a case with nothing, the case now falls back to its full candidate set.",
          f"* Main rows by how their account was obtained: {dict(how_main)} (of {len(dele)} deletion requests). "
          f"**Rows that depend on elimination or the seconds-phase stage: {how_main['eliminated'] + how_main['phase']}** "
          f"({how_main['eliminated']} eliminated, {how_main['phase']} phase); explicit links: {how_main['explicit']}.",
          f"* Anonymized analytics (main): {dict(how_ana)}.", ""]

    # ------------------------------------------------------------ 3. discovery detail
    amb = [c for c in no_acct_real if a_full.account_asg[c].how == "ambiguous"]
    kdist = collections.Counter(len(a_full.account_asg[c].candidates) for c in amb)
    a_hold = analytics_holdout(a_full, 0.3, seeds)
    a_single = analytics_holdout(a_full, 1.0 / 36, range(36))
    L += ["## 3. Discovery stages", "",
          "### Accounts (id-less, found through the activity timeline)", "",
          f"* real misses left: {len(no_acct_real)} = {len(amb)} ambiguous (candidates per row: {dict(sorted(kdist.items()))}) + "
          f"{len(no_acct_real) - len(amb)} with no candidate (no worker delete event for any free account in the window).",
          "* New general signals this phase (CHANGELOG rows 14-18): accounts linked to the user by a later snapshot count as the case's own when the worker deleted "
          "them in the window; a case whose preferred candidate was taken falls back to its full set; cohort narrowing off; "
          "**seconds-phase**: inside one case, the second-of-minute of every worker event sits at a fixed offset (per event kind) from the account-delete event, "
          "so the candidate whose offset fits the case's other events wins when it beats the runner-up by a clear margin (log-likelihood lead >= 2).", "",
          "### Anonymized analytics (id-less)", "",
          "* Pairs resolved by the 390/449 s policy-action chain teach the offset between the analytics anonymization and the account delete (41 s +-1 mod 60, "
          "35 of 36 pairs); a candidate is accepted when its offset fits and no other scored claimant of that record fits.", "",
          *HEADER, a_single.line("each chain-resolved pair hidden alone (36 runs)"), a_hold.line("30% of chain pairs hidden x 30 seeds"), ""]

    # ------------------------------------------------------------ 4. guessing
    P = sum(len(r.steps) for r in res_main.values())
    G = P + len(no_acct_real)        # every real-miss row lacks one account step (all 32 labeled answers verify the account); precision assumed 1.0 (32/32 samples)
    eff = f1_effect_of_guessing(P, P, G, dict(kdist))
    P2G = P2["steps"] + P2["missing_account_rows"] - 9
    eff2 = f1_effect_of_guessing(P2["steps"], P2["steps"], P2G, {k: v for k, v in P2["k"].items()})
    L += ["## 4. Guessing among k candidates versus omitting (behaviour NOT changed)", "",
          "Adding one step whose probability of being right is p raises predicted steps by 1 and true positives by p, so it improves micro-F1 only if p > F1/2 (about 49%). "
          "Assumptions, stated: step precision stays 1.0 as on the 32 samples, and each real-miss row lacks exactly one gold step (the account verification, present in all 32 labeled answers); "
          "other gold steps not reached by any record are ignored, which overstates F1 slightly.", "",
          f"Current run: {len(amb)} ambiguous rows, candidates per row {dict(sorted(kdist.items()))}; predicted steps {P}.", "",
          "| choice | expected F1 | change |", "|---|---|---|"]
    L += [f"| {n} | {pct(f)} | {100 * d:+.3f} pts |" for n, f, d in eff]
    L += ["", f"Phase 2 snapshot (the question as asked: {P2['ambiguous']} ambiguous rows, {sum(P2['k'].values()) - 0} rows by k {P2['k']}; predicted steps {P2['steps']}):", "",
          "| choice | expected F1 | change |", "|---|---|---|"]
    L += [f"| {n} | {pct(f)} | {100 * d:+.3f} pts |" for n, f, d in eff2]
    L += ["", "Reading: a uniform guess among 2 candidates has p = 50%, essentially the break-even, so it neither helps nor hurts on average; "
          "k = 3+ hurts. The seconds-phase stage removed most of this choice by turning the guess into evidence.", ""]

    # ------------------------------------------------------------ 5. remaining dev failures
    miss = collections.Counter()
    m_dev = score(gold, as_rows(res_samp), ids["dev"])
    extra = 0
    for c in m_dev.cases:
        for s in c.missing:
            miss[classify_missing(full[0], s)] += 1
        extra += len(c.extra)
    L += ["## 5. Remaining failures (dev samples only)", "", f"wrong/extra steps produced: **{extra}**", "",
          "| missing gold steps | reason |", "|---|---|"]
    L += [f"| {n} | {why} |" for why, n in miss.most_common()]
    (OUT / "phase3_results.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
