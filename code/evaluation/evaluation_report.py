#!/usr/bin/env python3
"""Generate code/evaluation/evaluation_report.md (the submission's evaluation write-up) from live measurements.

  python3 code/evaluation/evaluation_report.py

Nothing is typed in by hand except prose; every number is computed here (scorer, ablations, hold-out, synthetic cases, tests, determinism).
Tables copied from other generated files (baselines, loop log) are read from those files, which are produced by their own scripts.
"""
from __future__ import annotations

import collections
import contextlib
import hashlib
import importlib.util
import io
import re
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import extra_cases as xc  # noqa: E402
from auditor.audit import Auditor, Config  # noqa: E402
from auditor.dataset import load_dataset  # noqa: E402
from auditor.validate import validate_output_file  # noqa: E402
from holdout import HEADER, account_holdout, analytics_holdout  # noqa: E402
from phase2_report import as_rows, classify_missing, metrics_line, pct, run  # noqa: E402
from score import Row, assign_splits, build_report, read_rows, score  # noqa: E402

D = ROOT / "dataset"
OUT = ROOT / "code" / "evaluation"


def demote(md: str, by: int = 1) -> str:
    return re.sub(r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + by) + " ", md, flags=re.M)


def table_from(path: Path, header_prefix: str) -> list[str]:
    """The Markdown table in `path` whose header line starts with `header_prefix` (header, separator and rows)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith(header_prefix))
    end = start
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    return lines[start:end]


def load_module(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    cli = load_module("agent_cli", ROOT / "code" / "main.py")
    gold = read_rows(D / "sample_output.csv")
    split = assign_splits(gold)
    NT = "not tuned against in Phase 2-3"
    ids = {"dev": sorted(c for c in gold if split[c] == "dev"), NT: sorted(c for c in gold if split[c] == "heldout"), "all": sorted(gold)}
    ds = load_dataset(D)
    main_ids = ds.case_order

    a, res_s = run(Config(), ids["all"])
    pred = as_rows(res_s)
    res_m = {c: a.audit(c) for c in main_ids}
    m_all = score(gold, pred, ids["all"])
    m_dev = score(gold, pred, ids["dev"])
    m_nt = score(gold, pred, ids[NT])
    out_csv = ROOT / "output.csv"
    out_sha = hashlib.sha256(out_csv.read_bytes()).hexdigest() if out_csv.exists() else "(output.csv not generated yet)"
    cnt = collections.Counter(r.status for r in res_m.values())
    prov = [c for c in main_ids if res_m[c].provisional]

    L = ["# Evaluation report", "",
         "Generated by `python3 code/evaluation/evaluation_report.py`; every number is computed in that run (or read from a file produced by its own script, named where used). "
         "The submitted `output.csv` has sha256 `" + out_sha[:16] + "...`.", "",
         "**Honest scope.** The only labels are the 32 public samples. Their gold answers were all read in Phase 0 to infer the rules, so the 9 cases called "
         f"*{NT}* were simply not used while tuning in those phases; they are a weaker check than an independent set. The 518 evaluation requests have no labels here. "
         "No vision-model key was available in this environment, so **the vision path was tested only with fakes**; the submitted `output.csv` was produced without reading any screenshot.", "",
         "## 1. Headline", "",
         "| measure | dev (23) | " + NT + " (9) | all labeled (32) |", "|---|---|---|---|",
         f"| case-level status accuracy | {m_dev.status_correct}/{m_dev.n_cases} | {m_nt.status_correct}/{m_nt.n_cases} | {m_all.status_correct}/{m_all.n_cases} |",
         f"| step precision (strict, all six content fields) | {pct(m_dev.step_strict[0])} | {pct(m_nt.step_strict[0])} | {pct(m_all.step_strict[0])} |",
         f"| step recall (strict) | {pct(m_dev.step_strict[1])} | {pct(m_nt.step_strict[1])} | {pct(m_all.step_strict[1])} |",
         f"| step F1 (strict) | {pct(m_dev.step_strict[2])} | {pct(m_nt.step_strict[2])} | {pct(m_all.step_strict[2])} |",
         f"| exact ordered rows | {m_dev.exact_cases}/{m_dev.n_cases} | {m_nt.exact_cases}/{m_nt.n_cases} | {m_all.exact_cases}/{m_all.n_cases} |",
         f"| mean LCS ratio (sequence) | {pct(m_dev.mean_lcs_full)} | {pct(m_nt.mean_lcs_full)} | {pct(m_all.mean_lcs_full)} |", "",
         f"Main set (518 requests, no labels): COMPLETE {cnt['COMPLETE']}, INCOMPLETE {cnt['INCOMPLETE']}, NOT_APPLICABLE {cnt['NOT_APPLICABLE']}; "
         f"{len(prov)} provisional rows (section 6).", ""]

    # ------------------------------------------------------------------ 2. full scorer output
    text, _ = build_report(gold, pred, "both", 20, False, "final pipeline on the 32 labeled samples")
    L += ["## 2. Labeled samples: status, steps, fields, sequence", "",
          "Definitions: *strict* step match = all six content fields equal (phase, system_id, resource_id, operation, state, evidence_id); *relaxed* ignores evidence_id; "
          "*resource discovery* compares (system_id, resource_id) pairs; field-level accuracy aligns each gold step to a predicted step; *exact ordered rows* = the whole "
          "row identical in order; *LCS ratio* = longest common subsequence of the step sequences over the longer length. Failures are listed for dev cases only; "
          f"the {NT} cases contribute to the aggregates but their misses are not listed.", "", demote(text, 1), ""]

    # ------------------------------------------------------------------ 3. baselines
    L += ["## 3. Baselines and scorer sanity checks", "", "From `baseline_results.md` (`python3 code/evaluation/baseline.py`). B0/B1 are the floor; R2 must be 100% everywhere and R3 must "
          "keep step F1 but lose exact rows/LCS (the scorer sees order).", ""]
    L += table_from(OUT / "baseline_results.md", "| variant") + [""]

    # ------------------------------------------------------------------ 4. synthetic cases
    cases, rules = xc.parse()
    results, table = xc.run_all(cases, rules)
    cats = sorted({r["category"] for c in cases for r in c["resources"]})
    L += ["## 4. Additional evaluation cases (synthetic, derived from `deletion_rules.csv`)", "",
          f"**{sum(r['ok'] for r in results)}/{len(results)} pass.** Each case has a request, evidence, a rule basis and an expected answer (hand-written, then cross-checked by an independent oracle "
          "that re-derives it from the rule table, then compared with the pipeline). The full cases, with the expected step tables, are in "
          "[`extra_cases.md`](extra_cases.md) (Markdown, readable without running anything). They cover the categories no labeled sample covers (cache, e-mail delivery log, "
          "product telemetry, marketing profile, secondary identifier, object-storage attachment, four legal-hold variants), remediation ordering, non-deletion and mixed requests, "
          "prompt injection in a request, later evidence, evidence older than the request, a historical e-mail, and a decoy record of another person.", "",
          f"Categories exercised: {', '.join(cats)}.", "",
          "| case | what it tests | expected status | pipeline status | steps expected / produced | result |", "|---|---|---|---|---|---|", table, ""]

    # ------------------------------------------------------------------ 5. ablations
    variants = [("final pipeline (default)", Config()),
                ("no second-of-minute heuristics (`use_timing_heuristics=False`)", Config(use_timing_heuristics=False)),
                ("no timeline discovery (`use_discovery=False`)", Config(use_discovery=False)),
                ("no later-evidence linking (`allow_later_linking=False`)", Config(allow_later_linking=False)),
                ("cohort-snapshot narrowing ON (Phase 2 default; measured harmful)", Config(use_cohort_filter=True))]
    L += ["## 5. Ablations", "", "### 5.1 Labeled samples", "",
          "| variant / split | cases | status | step P | step R | step F1 | resource-discovery F1 | exact rows | mean LCS |", "|---|---|---|---|---|---|---|---|---|"]
    main_rows = []
    base_main = {c: res_m[c] for c in main_ids}
    for name, cfg in variants:
        aud, rr = run(cfg, ids["all"])
        pr = as_rows(rr)
        for sp in ids:
            L.append(metrics_line(f"{name} / {sp}", gold, pr, ids[sp]))
        am = Auditor(D, cfg)
        rm = {c: am.audit(c) for c in main_ids}
        dele = [c for c in main_ids if am.classification[c].label == "DELETION"]
        miss = sum(1 for c in dele if not any(s["system_id"] == "account_service" for s in rm[c].steps) and not rm[c].provisional)
        c2 = collections.Counter(r.status for r in rm.values())
        differ = sum(1 for c in main_ids if (rm[c].status, rm[c].steps) != (base_main[c].status, base_main[c].steps))
        main_rows.append(f"| {name} | {c2['COMPLETE']} / {c2['INCOMPLETE']} / {c2['NOT_APPLICABLE']} | {sum(len(r.steps) for r in rm.values())} | {miss} | {differ} |")
    noprov = Auditor(D, Config(provisional_rows=False))
    rn = {c: noprov.audit(c) for c in main_ids}
    c3 = collections.Counter(r.status for r in rn.values())
    main_rows.append(f"| provisional rows off (`provisional_rows=False`: the 9 screenshot-only requests back to NOT_APPLICABLE) | {c3['COMPLETE']} / {c3['INCOMPLETE']} / {c3['NOT_APPLICABLE']} | "
                     f"{sum(len(r.steps) for r in rn.values())} | - | {sum(1 for c in main_ids if (rn[c].status, rn[c].steps) != (base_main[c].status, base_main[c].steps))} |")
    L += ["", "Note on the *no later-evidence linking* rows: precision drops below 100% there (one wrong step on the samples). With the late snapshot ignored, one case loses the link to "
          "its own account, and elimination then gives it a neighbouring case's account: the same stolen-account mechanism as in section 7, visible here because the owner link is hidden. "
          "The default pipeline always uses later evidence for linking (never for state or citations, decision D3).",
          "", "### 5.2 Main set (no labels): what each switch changes", "",
          "| variant | COMPLETE / INCOMPLETE / NOT_APPLICABLE | steps produced | deletion rows without an account step (real misses) | rows that differ from the default |", "|---|---|---|---|---|", *main_rows, ""]
    seeds = range(30)
    L += ["### 5.3 Hold-out precision of the timeline discovery", "",
          "Cases whose resource is linked explicitly are hidden at random, the real discovery code runs, and each hidden case is `correct`, `wrong`, `stolen` "
          "(its resource went to another case) or `omitted` (`evaluation/holdout.py`).", "", *HEADER,
          account_holdout(a, 0.3, seeds).line("accounts, 30% hidden x 30 seeds, heuristics ON"),
          account_holdout(a, 0.3, seeds, use_timing_heuristics=False).line("accounts, 30% hidden x 30 seeds, timing heuristics OFF"),
          account_holdout(a, 0.5, seeds).line("accounts, 50% hidden x 30 seeds, heuristics ON"),
          account_holdout(a, 0.3, seeds, use_cohort=True).line("accounts, 30% hidden x 30 seeds, cohort narrowing ON (rejected)"),
          analytics_holdout(a, 0.3, seeds).line("anonymized analytics, 30% of chain pairs hidden x 30 seeds, heuristic ON"),
          analytics_holdout(a, 0.3, seeds, use_timing_heuristics=False).line("anonymized analytics, heuristic OFF"), "",
          "**What 100% precision does and does not prove.** It shows that, among cases whose answer is known from an explicit link, the discovery never assigned a wrong resource. "
          "It does not show the same rate on the cases that really have no link (their accounts are deleted and carry no identifier), which may be harder; it is measured on one "
          "dataset instance, so it says nothing about other seeds or about real logs; and the second-of-minute heuristics exploit this dataset's synthetic event timing (see section 8).", "",
          "### 5.4 Deterministic-only versus with the vision model", "",
          "* **Deterministic-only (what produced `output.csv`)**: the rows above. None of the 32 labeled samples depends on a screenshot, so the vision path cannot change a sample score.",
          "* **With the vision model: not measured.** No API key was available in this environment. The path (prompt, JSON schema, validation, cache, retries, usage log, fallback model) is "
          "covered by tests with a fake client, and `evaluation/show_image_readings.py` lets a reader compare each of the 11 PNGs with the model's reading. "
          f"The only rows that can change are the {len(prov)} provisional ones (`{', '.join(prov)}`), plus any row whose evidence includes a PNG that the structured data already covers.", ""]

    # ------------------------------------------------------------------ 6. provisional rows
    L += ["## 6. Provisional rows", "",
          f"{len(prov)} deletion requests have a screenshot as their only state evidence. Without a vision-model key each is answered `INCOMPLETE` with three steps "
          "(finding on the record the data catalog ties to the user inside the window, citing the in-window screenshot of the same system; remediation; verification). "
          "The state is assumed, not read. They are listed in `output.notes.md`, in `phase4_results.md` and below.", "",
          "| case | reported_status | provisional steps |", "|---|---|---|"]
    for c in prov:
        L.append(f"| {c} | {a.requests[c].reported_status} | " + " -> ".join(f"{s['operation']} `{s['resource_id']}`" for s in res_m[c].steps) + f" (finding cites `{res_m[c].steps[0]['evidence_id']}`) |")
    L.append("")

    # ------------------------------------------------------------------ 7. failures found and improvements
    L += ["## 7. Failures found and improvements made", "",
          "The loop log below is `CHANGELOG.md` verbatim: each row is a change with the motivation, the score before and after, and whether it was kept or reverted "
          "(rows 1 and 9 were reverted/rejected). Phase 3 and 4 also found these defects by measurement rather than by looking at scores:", "",
          "* **Stolen accounts**: an account linked to its owner only by a later snapshot was handed to a neighbouring case by elimination; per-case hold-out scoring could not see it "
          "(a labeled sample exposed it). The hold-out now counts `stolen` resources (rows 15-17).",
          "* **Cohort-snapshot narrowing** looked right on the samples and was harmful in hold-out (precision 85%); it is off by default (row 17).",
          "* **CLI differed from the library**: `main.py` had the cohort filter on while `Config()` had it off, so the file we would have submitted differed from the reported numbers on 18 rows; "
          "now guarded by a test that fails on the old default (row 17).",
          "* **'No later-evidence' ablation leaked later evidence** through late-linked accounts, and those links were not in the log; fixed and logged (row 19).",
          "* **A wrong NOT_APPLICABLE placeholder** for deletion requests whose only evidence is a screenshot; replaced by provisional INCOMPLETE rows (row 23).",
          "* **An instruction-like status word extracted from an image could have flipped a state**; model-written fields are now sanitised (row 28).", ""]
    L += table_from(OUT / "CHANGELOG.md", "| #") + [""]

    # ------------------------------------------------------------------ 8. remaining failures and known weaknesses
    miss = collections.Counter()
    extra = 0
    for c in m_dev.cases:
        for s in c.missing:
            miss[classify_missing(a, s)] += 1
        extra += len(c.extra)
    dele = [c for c in main_ids if a.classification[c].label == "DELETION"]
    amb = sum(1 for c in dele if a.account_asg.get(c) and a.account_asg[c].how == "ambiguous")
    none_ = sum(1 for c in dele if a.account_asg.get(c) and a.account_asg[c].how == "none")
    ana_amb = sum(1 for c in main_ids if a.analytics_asg.get(c) and a.analytics_asg[c].how == "ambiguous")
    L += ["## 8. Remaining failures and known weaknesses", "",
          f"* dev samples: **{extra} wrong or extra steps**, missing gold steps: " + (", ".join(f"{n} x {why}" for why, n in miss.most_common()) or "none") + ".",
          f"* main set: {amb} deletion rows with an ambiguous account (candidates cannot be separated) and {none_} with no candidate; {ana_amb} ambiguous anonymized-analytics rows. "
          "Such steps are omitted rather than guessed (a guess among 2 candidates is break-even for F1, among 3 or more it loses; see `phase3_results.md` section 4).",
          "* **The second-of-minute heuristics exploit regularities of this dataset's synthetic event timing and would not be reliable on production logs.** They can be switched off with "
          "`--no-timing-heuristics`; section 5 shows what that costs (step F1 on the samples, rows without an account step).",
          "* The legal-hold exposed-identifier shape and every category without a labeled sample are verified only by the synthetic cases.",
          "* Classifier lexicons cover eight languages; other languages end as ambiguous and therefore NOT_APPLICABLE (a model tie-break hook exists in `classify.py` but `main.py` does not enable it; tested with a fake client only).",
          "* Constants (time windows, chain gaps, margins) were set from the labeled data; they are documented and unit-tested.", ""]

    # ------------------------------------------------------------------ 9. determinism, robustness, tests
    cli_main = cli.main
    with tempfile.TemporaryDirectory() as d:
        outs = []
        for i in (1, 2):
            o = Path(d) / f"run{i}.csv"
            with contextlib.redirect_stderr(io.StringIO()):
                code = cli_main(["--out", str(o), "--images", "off"])
            outs.append((code, o.read_bytes()))
        errs = [i for i in validate_output_file(Path(d) / "run1.csv", ds) if i.severity == "error"]
    suite = unittest.defaultTestLoader.discover(str(ROOT / "code" / "tests"), top_level_dir=str(ROOT / "code"))
    n_tests = suite.countTestCases()
    result = unittest.TextTestRunner(stream=io.StringIO(), verbosity=0).run(suite)
    L += ["## 9. Determinism, robustness, tests", "",
          f"* two full runs on all {len(main_ids)} requests (deterministic path, no model): exit codes {outs[0][0]}, {outs[1][0]}; files **{'byte-identical' if outs[0][1] == outs[1][1] else 'DIFFERENT'}**; "
          f"validator errors on the written file: {len(errs)}. The committed `output.csv` is byte-identical to a fresh run: "
          f"**{'yes' if out_csv.exists() and out_csv.read_bytes() == outs[0][1] else 'NO'}**.",
          f"* test suite: **{n_tests} tests, {len(result.failures)} failures, {len(result.errors)} errors** (`python3 -m unittest discover -s code/tests -t code`): scorer and validator, classifier "
          "(112 request sentences, paraphrases), pipeline stages, the synthetic cases, robustness (malformed rows, corrupt files, API timeouts / rate limits / invalid JSON / refusals "
          "with a fake client, injection strings in model-written fields), packaging rules, no-hardcoding scan and secrets scan.",
          "* model nondeterminism (cleared-cache rerun with a real model): **not measured** (no key); cold / warm / cleared-cache agreement is tested with a fake client.", ""]

    # ------------------------------------------------------------------ 10. unmeasured
    L += ["## 10. Not measured", "",
          "* vision-model accuracy on the 11 screenshots, its run-to-run variance, token usage and cost (no API key was available; `usage_report.md` states 0 calls);",
          f"* the true answers of the {len(prov)} provisional rows;",
          "* the exposed-identifier shape of a legal-hold record, and all policy categories without a labeled sample, beyond the synthetic cases;",
          "* behaviour on another dataset instance (another generator seed) and whether the timing heuristics hold there;",
          f"* the accuracy of the discovery on the {none_} + {amb} deletion rows that really lack an account link (hold-out covers cases that have a link);",
          "* an independent test set: the 32 labels were all seen in Phase 0.", ""]
    (OUT / "evaluation_report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'evaluation_report.md'} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
